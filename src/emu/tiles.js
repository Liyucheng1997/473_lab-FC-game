export const T = {}; // 名字 → 图块编号

function put(ppu, index, rows) {
  if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error('图块尺寸不对：' + index);
  rows.forEach((r, y) => {
    for (let x = 0; x < 8; x++) ppu.chr[index * 64 + y * 8 + x] = r[x] === '.' ? 0 : +r[x];
  });
}

export function buildTiles(ppu) {
  ppu.chr.fill(0);
  for (const [ch, rows] of Object.entries(FONT)) {
    const out = rows.map((v) => {
      let s = '.';
      for (let b = 4; b >= 0; b--) s += v & (1 << b) ? '3' : '.';
      return s + '..';
    });
    out.push('........');
    put(ppu, ch.charCodeAt(0), out);
  }
  let next = 0x80;
  for (const [name, rows] of Object.entries(ART)) { T[name] = next; put(ppu, next++, rows); }
  for (const [name, rows] of Object.entries(BIG)) {
    if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error('大图形尺寸不对：' + name);
    T[name] = next;
    for (let q = 0; q < 4; q++) {
      const ox = (q & 1) * 8, oy = (q >> 1) * 8;
      put(ppu, next++, rows.slice(oy, oy + 8).map((r) => r.slice(ox, ox + 8)));
    }
  }
}
